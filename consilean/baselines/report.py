"""Assemble the Sprint 0 baseline report and write the generated tables."""

from __future__ import annotations

import json
import math
from pathlib import Path

from consilean.baselines.constants import drop_instance_constants, rank_constants
from consilean.baselines.text import distances_for, rank_text
from consilean.ingest.corpus import CorpusSpec
from consilean.ingest.declarations import load_declarations
from consilean.ingest.graph import directed_internal_edges, faithful_module_graph, undirected_distances
from consilean.ingest.observations import load_entrypoints
from consilean.vendor.import_graph import build, summarise

GENERATING_COMMAND = "uv run consilean-baseline"
TWIN_SHORT = {
    "isSquare_neg_one_mod_markovNumber",
    "exists_sq_modEq_neg_one_markovNumber",
}


def build_report(root: Path, spec: CorpusSpec) -> dict:
    """Faithful pilots plus the comment-stripping and instance-filter variants."""
    declarations = load_declarations(root, blank_block_comments=False)
    stripped = load_declarations(root, blank_block_comments=True)
    graph = faithful_module_graph(root)
    distances = distances_for(graph)
    text = rank_text(declarations, distances)
    text["modules"] = len(graph)
    text["directed_internal_import_edges"] = directed_internal_edges(graph)
    stripped_text = rank_text(stripped, distances)

    corrected_graph = build(root, spec.namespace)
    corrected_summary = summarise(corrected_graph, spec.namespace)
    corrected_summary["top_in_degree"] = [
        [module, degree] for module, degree in corrected_summary["top_in_degree"]
    ]
    corrected_distances = undirected_distances(corrected_graph)

    entrypoints = load_entrypoints(root)
    with_deps = {
        name: entry.type_dependencies
        for name, entry in entrypoints.items()
        if entry.type_dependencies
    }
    constants = rank_constants(with_deps)
    dropped = rank_constants(drop_instance_constants(with_deps))
    dropped["drop_instances"] = True

    return {
        "generating_command": GENERATING_COMMAND,
        "corpus": {
            "repo": spec.repo,
            "revision": spec.revision,
            "namespace": spec.namespace,
            "lean": spec.lean,
            "mathlib": spec.mathlib,
        },
        "faithful": {
            "text": text,
            "constants": constants,
        },
        "corrected": {
            "import_graph": corrected_summary,
            "text_strip_comments": {
                "public_declarations": stripped_text["public_declarations"],
                "pairs_above_cutoff": stripped_text["pairs_above_cutoff"],
                "twin": stripped_text["twin"],
            },
            "constants_drop_instances": {
                "entrypoints": dropped["entrypoints"],
                "pairs": dropped["pairs"],
                "twin": dropped["twin"],
                "top": dropped["top"],
            },
            "twin_module_distance": _twin_distance(declarations, distances, corrected_distances),
        },
    }


def write_generated(repo: Path, report: dict) -> tuple[Path, Path]:
    """Write the JSON and markdown tables under `docs/generated/`."""
    out = repo / "docs" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    json_path = out / "leanfrontier-79800a5.json"
    md_path = out / "leanfrontier-79800a5.md"
    json_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    md_path.write_text(render_markdown(report), encoding="utf-8")
    return json_path, md_path


