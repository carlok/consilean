def print_report(report: dict) -> None:
    """Print the locked lines and the corrected twin lines."""
    text = report["faithful"]["text"]
    constants = report["faithful"]["constants"]
    corrected = report["corrected"]
    print(
        f"{text['public_declarations']} public declarations in {text['modules']} modules; "
        f"{text['directed_internal_import_edges']} directed internal import edges"
    )
    _print_twin("Known duplicate (the sqrt(-1) twin), text", text["twin"])
    print(
        f"{constants['entrypoints']} entrypoints with recorded type dependencies; "
        f"{constants['pairs']} pairs"
    )
    _print_twin("sqrt(-1) twin under the constants view", constants["twin"])
    if constants["twin"]:
        print("  shared constants:", constants["twin"]["shared_constants"])
    print(
        "strip_comments text view: "
        f"{corrected['text_strip_comments']['public_declarations']} declarations, "
        f"{corrected['text_strip_comments']['pairs_above_cutoff']} pairs above 0.25"
    )
    _print_twin("sqrt(-1) twin under strip_comments", corrected["text_strip_comments"]["twin"])
    graph = corrected["import_graph"]
    print(
        f"corrected import graph: {graph['modules']} modules, "
        f"{graph['internal_edges']} internal edges, {graph['external_edges']} external edges"
    )
    dropped = corrected["constants_drop_instances"]
    print(f"constants view with inst-names dropped: {dropped['entrypoints']} entrypoints, {dropped['pairs']} pairs")
    _print_twin("sqrt(-1) twin with inst-names dropped", dropped["twin"])


def _twin_distance(declarations, faithful, corrected) -> dict:
    modules = [decl.module for decl in declarations if decl.name in TWIN_SHORT]
    if len(modules) != 2:
        return {"faithful": None, "corrected": None, "modules": modules}
    left, right = modules
    return {
        "modules": [left, right],
        "faithful": _lookup(faithful, left, right),
        "corrected": _lookup(corrected, left, right),
    }


def _lookup(distances: dict[str, dict[str, int]], left: str, right: str) -> int | None:
    if left not in distances:
        return None
    distance = distances[left].get(right, math.inf)
    if math.isinf(distance):
        return None
    return distance


def _pair_row_distance(distance: int | None) -> str:
    return "∞" if distance is None else str(distance)


def _fmt_distance(distance: int | None) -> str:
    return "none" if distance is None else str(distance)


def _bullet(label: str, value: object) -> str:
    return f"- {label}: {value}"


def _twin_line(kind: str, twin: dict | None) -> str:
    if not twin:
        return f"- sqrt(-1) twin ({kind}): not in the ranked pairs"
    distance = ""
    if "distance" in twin:
        distance = f", distance {_pair_row_distance(twin['distance'])}"
    return (
        f"- sqrt(-1) twin ({kind}): score {twin['score']:.2f}, "
        f"rank {twin['rank']} of {twin['of']}{distance}"
    )


def _print_twin(label: str, twin: dict | None) -> None:
    if not twin:
        print(f"{label}: not in the ranked pairs")
        return
    extra = ""
    if "distance" in twin:
        extra = f", distance {_pair_row_distance(twin['distance'])}"
    print(f"{label}: score {twin['score']:.2f}, rank {twin['rank']} of {twin['of']}{extra}")


def _constant_lists(twin: dict | None) -> str:
    if not twin:
        return ""
    return "\n".join(
        [
            "Shared constants:",
            "",
            _code_list(twin["shared_constants"]),
            "",
            "Only in the IsSquare form:",
            "",
            _code_list(twin["only_is_square"]),
            "",
            "Only in the ModEq form:",
            "",
            _code_list(twin["only_mod_eq"]),
        ]
    )


def _code_list(items: list[str]) -> str:
    if not items:
        return "(none)"
    return "\n".join(f"- `{item}`" for item in items)


def _text_table(rows: list[dict]) -> str:
    header = "| score | distance | left | right |"
    rule = "|---:|---:|---|---|"
    body = [
        f"| {row['score']:.2f} | {_pair_row_distance(row['distance'])} | `{_short(row['left'])}` | `{_short(row['right'])}` |"
        for row in rows
    ]
    return "\n".join([header, rule, *body]) if body else "(none)"


def _constants_table(rows: list[dict]) -> str:
    header = "| score | left | right |"
    rule = "|---:|---|---|"
    body = [
        f"| {row['score']:.2f} | `{_short(row['left'])}` | `{_short(row['right'])}` |"
        for row in rows
    ]
    return "\n".join([header, rule, *body]) if body else "(none)"


def _short(name: str) -> str:
    return name.removeprefix("LeanFrontier.")
