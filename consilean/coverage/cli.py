"""Write a coverage table for Mathlib, Prove2Me, and Tau Ceti. No pairs."""

from __future__ import annotations

import argparse
import json

from consilean.coverage.report import coverage_row, git_revision
from consilean.ingest.corpus import ensure_checkout, load_spec, repo_root

GENERATING_COMMAND = "uv run consilean-coverage"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    root = repo_root()
    rows = []
    mathlib_project = root.parent / "mathlib-v4.34.0-reuse"
    mathlib_src = mathlib_project / ".lake" / "packages" / "mathlib"
    if not (mathlib_src / "Mathlib").is_dir():
        mathlib_src = mathlib_project
    if (mathlib_src / "Mathlib").is_dir():
        rows.append(
            coverage_row(
                corpus="Mathlib",
                revision=git_revision(mathlib_src) or _manifest_rev(mathlib_project, "mathlib"),
                root=mathlib_src,
                namespace="Mathlib",
                note="Local v4.34.0 tree. Coverage only. No pair ranking.",
            )
        )
    else:
        rows.append(_missing("Mathlib", "local v4.34.0 tree not found"))
    prove = root.parent / "prove2me" / "missions"
    if prove.is_dir():
        rows.append(
            coverage_row(
                corpus="Prove2Me",
                revision=None,
                root=prove,
                search_root=prove,
                note="Local missions tree, not one Lean package. No import graph.",
            )
        )
    else:
        rows.append(_missing("Prove2Me", "local missions tree not found"))
    rows.append(_tau_ceti(root))
    report = {"generating_command": GENERATING_COMMAND, "rows": rows}
    out = root / "docs" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    json_path = out / "coverage.json"
    md_path = out / "coverage.md"
    json_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    md_path.write_text(_markdown(report), encoding="utf-8")
    print(f"wrote {md_path}")


def _tau_ceti(root):
    spec_path = root / "corpora" / "tauceti.toml"
    if not spec_path.is_file():
        return _missing("Tau Ceti", "no pin at corpora/tauceti.toml")
    spec = load_spec(spec_path)
    try:
        checkout = ensure_checkout(spec, root / "corpora" / "cache" / "TauCeti", override_env=None)
    except SystemExit as exc:
        return _missing("Tau Ceti", str(exc))
    namespace = spec.namespace if (checkout / spec.namespace).is_dir() else None
    return coverage_row(
        corpus="Tau Ceti",
        revision=spec.revision,
        root=checkout,
        namespace=namespace,
        search_root=None if namespace else checkout,
        note="" if namespace else "No single namespace directory. Files counted from the checkout root. No import graph.",
    )


def _manifest_rev(project, name: str) -> str | None:
    path = project / "lake-manifest.json"
    if not path.is_file():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    for package in data.get("packages", []):
        if package.get("name") == name:
            return package.get("rev")
    return None


def _missing(corpus: str, note: str) -> dict:
    return {
        "corpus": corpus,
        "revision": None,
        "lean_files": None,
        "public_declarations": None,
        "parsed": None,
        "note": note,
        "import_modules": None,
        "internal_edges": None,
    }


def _markdown(report: dict) -> str:
    lines = [
        "# Corpus coverage",
        "",
        f"Generated by `{report['generating_command']}`.",
        "",
        "This is not a ranking and not a measurement of H1, H2, or H3.",
        "",
        "Do not edit this file by hand. Re-run the command.",
        "",
        "| corpus | revision | lean files | declarations | parsed | modules | internal edges |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    notes = []
    for row in report["rows"]:
        lines.append(
            "| {corpus} | `{revision}` | {files} | {decls} | {parsed} | {modules} | {edges} |".format(
                corpus=row["corpus"],
                revision=row["revision"] or "",
                files=_cell(row["lean_files"]),
                decls=_cell(row["public_declarations"]),
                parsed=_cell(row["parsed"]),
                modules=_cell(row["import_modules"]),
                edges=_cell(row["internal_edges"]),
            )
        )
        if row["note"]:
            notes.append(f"{row['corpus']}: {row['note']}")
    lines.append("")
    lines.extend(notes)
    lines.append("")
    return "\n".join(lines)


def _cell(value: object) -> str:
    return "" if value is None else str(value)
